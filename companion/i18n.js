// Lingue del configuratore web. Il sorgente è scritto in italiano: le frasi italiane
// sono le chiavi e qui accanto c'è l'inglese. Tre lingue indipendenti:
// - interfaccia (`uiLang`): preferenza del browser, in camtag.ui.v1 (`lang`);
//   all'inizio quella del sistema se è l'italiano, altrimenti l'inglese;
// - card (`state.lang`, nel progetto): le scritte disegnate sulle schermate;
// - X3 (`state.deviceLang`): lang= in settings.ini, le scritte del firmware.
// `t()` traduce per l'interfaccia, `tc()` per le card, `tl(lang, …)` per una
// lingua data. `{}` sono i valori, nell'ordine; `{0}`, `{1}`… se l'inglese li
// vuole in un altro ordine. h() traduce da sé testi e attributi che sono una
// chiave esatta: le frasi con valori passano da t(). Una frase nuova
// nell'interfaccia va aggiunta qui, se no in inglese resta in italiano
// (`?i18n=check` nell'indirizzo la segnala in console).
const LANGS = { en: 'English', it: 'Italiano' };
const uiLang = (() => {
  try { const l = JSON.parse(localStorage.getItem('camtag.ui.v1'))?.lang; if (l in LANGS) return l; } catch {}
  return /^it\b/i.test(navigator.language || '') ? 'it' : 'en';
})();

